CREATE TABLE users (
 id INTEGER PRIMARY KEY,
 username TEXT NOT NULL COLLATE NOCASE UNIQUE,
 password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK(role IN ('ADMIN','ACCOUNTANT','BILLER','VIEWER')),
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))
);
ALTER TABLE audit_log ADD COLUMN actor_id INTEGER REFERENCES users(id);
